// A flowchart prompt, turned into a WHILE program (test only) and run.
function flowCheck(prompt) {
  const L = prompt.split('\n');
  const i0 = L.indexOf('Start');
  if (i0 < 0) return null;
  const pre = [], vars = new Set(['Count', 'ZYes', 'ZIn']);
  let i = i0 + 1;
  while (!L[i].startsWith('Decision: ')) pre.push(L[i++]);
  const dec = L[i].slice(10).replace(/\?$/, '');
  const yes = L[i + 1].trim().replace(/^Yes: /, '').replace(/, then the arrow goes back to the decision\.$/, '').split(', then ');
  const no = L[i + 2].trim().replace(/^No: /, '').replace(/,? ?then Stop\.$|^Stop\.$/, '').split(', then ').filter(Boolean);
  for (const l of [...pre, ...yes, ...no]) { const m = l.match(/^(?:INPUT\s+)?(\w+)\s*(?:←|$)/); if (m && !/^(OUTPUT|Start)$/.test(m[1])) vars.add(m[1]); }
  const prog = [...[...vars].map((v) => `DECLARE ${v} : INTEGER`), 'ZYes <- 0', 'ZIn <- 0', ...pre, `WHILE ${dec} DO`,
    ...yes.flatMap((l) => (/^INPUT /.test(l) ? [l, 'ZIn <- ZIn + 1'] : [l])), 'ZYes <- ZYes + 1', 'ENDWHILE', ...no, 'OUTPUT ZYes', 'OUTPUT Count', 'OUTPUT ZIn'];
  const r = PE.runPseudocode(prog.join('\n'), {}, 20000, Array.from({ length: 30 }, () => '1'));
  assert(!r.error, 'flowchart program runs: ' + (r.error && r.error.message) + '\n' + prog.join('\n'));
  const o = r.outputs.map(String);
  return { outs: o.slice(0, -3), yes: o.at(-3), stop: o.at(-2), ins: o.at(-1) };
}
